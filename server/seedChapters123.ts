export function seedChapters1To3IfNeeded(): void {
  const alreadySeeded = db
    .prepare("SELECT value FROM app_settings WHERE key = 'seeded_ch1_ch2_ch3_v1'")
    .get() as { value: string } | undefined;

  if (alreadySeeded?.value === 'true') {
    return;
  }

  const updateChapter = db.prepare(
    `UPDATE chapters SET title = ?, description = ?, updated_at = datetime('now')
     WHERE chapter_number = ?`
  );

  const checkExisting = db.prepare(
    `SELECT id FROM questions WHERE scope = 'chapter' AND chapter_number = ? AND question_text = ?`
  );

  const insertQuestion = db.prepare(
    `INSERT INTO questions (scope, chapter_number, question_text, option_a, option_b, option_c, option_d, correct_option, explanation)
     VALUES ('chapter', ?, ?, ?, ?, ?, ?, ?, '')`
  );

  const allQuestions = [
    ...CHAPTER_1_QUESTIONS,
    ...CHAPTER_2_QUESTIONS,
    ...CHAPTER_3_QUESTIONS,
  ];

  const tx = db.transaction(() => {
    updateChapter.run(
      'Work, Power, and Machines',
      'Section One: Work and Power · Section Two: Machines (25 Questions)',
      1
    );
    updateChapter.run(
      'Energy',
      'Physics (Energy Chapter 2) · Top Ministerial Exam Questions (37 Questions)',
      2
    );
    updateChapter.run(
      'Heat & Temperature',
      'Heat, Temperature & Specific Heat · Comprehensive Question Bank (50 Questions)',
      3
    );

    for (const q of allQuestions) {
      const exists = checkExisting.get(q.chapterNumber, q.questionText);
      if (!exists) {
        insertQuestion.run(
          q.chapterNumber,
          q.questionText,
          q.optionA,
          q.optionB,
          q.optionC,
          q.optionD,
          q.correctOption
        );
      }
    }

    db.prepare(
      "INSERT OR REPLACE INTO app_settings (key, value) VALUES ('seeded_ch1_ch2_ch3_v1', 'true')"
    ).run();

    // Notify existing students that Chapters 1-3 questions have been added
    const students = db
      .prepare("SELECT id FROM users WHERE role = 'student'")
      .all() as Array<{ id: number }>;
    const insertNotif = db.prepare(
      `INSERT INTO notifications (user_id, title, body, category, link_tab)
       VALUES (?, ?, ?, 'question', 'multiple-choice')`
    );
    for (const st of students) {
      insertNotif.run(
        st.id,
        'Chapters 1–3 Questions Published',
        '112 questions for Chapter 1 (Work, Power, and Machines), Chapter 2 (Energy), and Chapter 3 (Heat & Temperature) are now available.'
      );
    }
  });

  tx();
}
